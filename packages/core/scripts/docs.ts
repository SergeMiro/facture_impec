function messages(rule: Rule): string {
  return (rule.variants ?? [undefined])
    .map((v) => {
      const key = messageKeys(rule, v).message;
      return isMessageKey(key) ? t(key) : `(missing ${key})`;
    })
    .map(cell)
    .join('<br>');
}

const level = (rule: Rule) =>
  `${rule.severity === 'error' ? 'error' : 'warning'}${rule.autoFixable ? ', auto-fix' : ''}`;

export function renderRules(cenIds: readonly string[]): string {
  const ours = new Set(RULES.map((r) => r.id));
  const notApplied = cenIds
    .filter((id) => !ours.has(id))
    .map((id) => ({ id, why: NOT_APPLIED.find((n) => n.ids.test(id))?.why }));
  const unexplained = notApplied.filter((n) => n.why === undefined).map((n) => n.id);
  if (unexplained.length > 0)
    throw new Error(`CEN rules without a rule or a reason: ${unexplained.join(', ')}`);

  const errors = RULES.filter((r) => r.severity === 'error').length;
  const lines = [
    HEADER('pnpm --filter @fi/core gen:docs'),
    '',
    '# Validation rules',
    '',
    `${RULES.length} rules: ${errors} errors and ${RULES.length - errors} warnings. ` +
      `${cenIds.length - notApplied.length} of the ${cenIds.length} CEN EN 16931 rules are applied; the others are listed at the end with the reason.`,
    '',
    '## How to read this',
    '',
    '- **error** blocks sending; **warning** is shown but does not block.',
    '- **auto-fix** marks pure formatting fixes that cannot change the meaning (spaces, dots, date format, decimal comma). ' +
      'An auto-fixable issue hides the other issues on the same path: once the fix is applied, validation runs again and shows what is left.',
    '- The message column is the French text shown to the user (packages/shared/i18n/fr.json); `{value}`, `{field}`, `{rate}`, `{category}`, `{mention}` and `{last}` are filled in per issue.',
    '- Some rules read the context given by the caller, not the invoice alone: today in Europe/Paris (BR-FR-CO-01), the invoices already issued (BR-FR-CO-02, FF-NUM-01, FF-NUM-02, FF-CN-01; silent when the history is unknown), ' +
      'the seller option for VAT on debits (FF-DEB-01) and customer settings (FF-PO-01 purchase order required, BR-FR-14 delivers elsewhere, DGFIP-G2.32 public entity).',
    '- BR-FR-DEC-01 runs while reading an XML file: the model holds cents and cannot represent a third decimal.',
    '- Every rule has at least one failing case in fixtures/invalid and passes on the golden invoices in fixtures/golden (packages/core/src/rules/rules.test.ts).',
    '',
  ];
  for (const { source, title, intro } of SOURCES) {
    const rules = RULES.filter((r) => r.source === source);
    lines.push(`## ${title}`, '', intro, '', `${rules.length} rules.`, '');
    lines.push('| Id | Level | Scope | BT | Checks | Message |', '|---|---|---|---|---|---|');
    for (const r of rules)
      lines.push(
        `| ${r.id} | ${level(r)} | ${r.scope} | ${r.bt.join(', ')} | ${cell(r.summary)} | ${messages(r)} |`,
      );
    lines.push('');
  }
  lines.push(
    '## CEN rules not applied',
    '',
    'The reference validator (CEN XSLT, M1 oracle tests) still runs every one of them on the generated XML.',
    '',
    '| Id | Why |',
    '|---|---|',
    ...notApplied.map((n) => `| ${n.id} | ${cell(n.why ?? '')} |`),
    '',
    'BR-CL-17 and BR-CL-18 cover the same values in both syntaxes but split them differently: CEN checks VAT breakdown categories under BR-CL-17 in UBL and under BR-CL-18 in CII. Here BR-CL-17 covers document allowances and charges, BR-CL-18 lines and the VAT breakdown; the oracle tests treat the two ids as one.',
    '',
  );
  return lines.join('\n');
}

export function renderStateMachine(): string {
  const lines = [
    HEADER('pnpm --filter @fi/core gen:docs'),
    '',
    '# Invoice state machine',
    '',
    '`transition(from, event, actor)` in packages/core/src/state.ts is the only way to change an invoice status. ' +
      'It refuses an event that is not allowed from the current state, or by that kind of actor.',
    '',
    `States (${STATES.length}): ${STATES.map((s) => `\`${s}\``).join(', ')}.`,
    '',
    `Terminal states: ${TERMINAL_STATES.map((s) => `\`${s}\``).join(', ')}.`,
    '',
    '```mermaid',
    'stateDiagram-v2',
    '  [*] --> draft',
  ];
  for (const event of EVENTS) {
    const { from, to } = TRANSITIONS[event];
    for (const f of from) lines.push(`  ${f} --> ${to}: ${event}`);
  }
  for (const s of TERMINAL_STATES) lines.push(`  ${s} --> [*]`);
  lines.push(
    '```',
    '',
    '| Event | From | To | Who | Note |',
    '|---|---|---|---|---|',
    ...EVENTS.map((event) => {
      const { from, to, by, note } = TRANSITIONS[event];
      return `| ${event} | ${from.join(', ')} | ${to} | ${by.join(', ')} | ${cell(note)} |`;
    }),
    '',
    'Who: `user` (a click in the add-in), `pdp` (platform webhook or polling), `system` (our jobs and the deterministic core), `agent` (one of our agents, e.g. CollectAgent).',
    '',
  );
  return lines.join('\n');
}
