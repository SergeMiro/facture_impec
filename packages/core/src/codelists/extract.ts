// Extracts the EN 16931 code lists from the CEN `EN16931-{CII,UBL}-codes.sch` files, so the lists we
// accept are exactly the ones the official validator accepts (docs/research/FORMATS.md §4).
// Used by scripts/codelists.ts to write generated.ts, and by a test that fails on any drift.

const ASSERT = /<assert\b[^>]*?\btest="([^"]*)"[^>]*?\bid="(BR-CL-\d+)"/gs;
const CONTAINS = /contains\(\s*'\s([^']*?)\s'\s*,\s*concat\(/g;
const MIME = /@mimeCode\s*=\s*'([^']+)'/g;

export type CodeLists = Record<string, string[]>;

export function extractCodeLists(schematron: string): CodeLists {
  const lists: CodeLists = {};
  for (const [, test = '', id = ''] of schematron.matchAll(ASSERT)) {
    const codes = new Set(lists[id] ?? []);
    for (const [, list = ''] of test.matchAll(CONTAINS)) {
      for (const code of list.split(/\s+/)) if (code) codes.add(code);
    }
    for (const [, mime = ''] of test.matchAll(MIME)) codes.add(mime);
    lists[id] = [...codes].sort();
  }
  return lists;
}

/** The lists our model uses, by rule id. Ids that only alias another list are left out. */
export const EXPORTED: Record<string, string> = {
  'BR-CL-01': 'invoiceTypeCodes',
  'BR-CL-04': 'currencyCodes',
  'BR-CL-07': 'referenceQualifiers',
  'BR-CL-08': 'noteSubjectCodes',
  'BR-CL-10': 'icdCodes',
  'BR-CL-13': 'itemClassificationCodes',
  'BR-CL-14': 'countryCodes',
  'BR-CL-16': 'paymentMeansCodes',
  'BR-CL-17': 'vatCategoryCodes',
  'BR-CL-19': 'allowanceReasonCodes',
  'BR-CL-20': 'chargeReasonCodes',
  'BR-CL-22': 'vatexCodes',
  'BR-CL-23': 'unitCodes',
  'BR-CL-24': 'mimeCodes',
  'BR-CL-25': 'easCodes',
};

const wrap = (codes: string[]): string => {
  const lines: string[] = [];
  let line = '';
  for (const code of codes) {
    if (line && line.length + code.length + 1 > 96) {
      lines.push(line);
      line = code;
    } else line = line ? `${line} ${code}` : code;
  }
  if (line) lines.push(line);
  return lines.join('\n');
};

export interface Source {
  name: string;
  sha256: string;
  text: string;
}

/**
 * Renders generated.ts. A list is syntax-neutral when CII and UBL agree; the two known differences
 * (BR-CL-06, the BT-8 codes, and BR-CL-10, where UBL also accepts SEPA) are rendered per syntax.
 */
export function renderGenerated(version: string, cii: Source, ubl: Source): string {
  const c = extractCodeLists(cii.text);
  const u = extractCodeLists(ubl.text);
  const out = [
    '// GENERATED by scripts/codelists.ts from the vendored CEN files. Do not edit by hand.',
    `// CEN EN 16931 validation artefacts ${version}`,
    `// ${cii.name} sha256 ${cii.sha256}`,
    `// ${ubl.name} sha256 ${ubl.sha256}`,
    '',
    `export const CEN_VERSION = '${version}';`,
    '',
    'const words = (text: string): ReadonlySet<string> => new Set(text.trim().split(/\\s+/));',
    '',
  ];
  for (const [id, name] of Object.entries(EXPORTED)) {
    // BR-CL-08 (note subject codes) exists in CII only.
    const ciiCodes = c[id] ?? u[id] ?? [];
    const ublCodes = u[id] ?? ciiCodes;
    const common = ciiCodes.filter((code) => ublCodes.includes(code));
    out.push(`/** ${id}: ${common.length} codes. */`);
    out.push(`export const ${name} = words(\`\n${wrap(common)}\n\`);`, '');
  }
  out.push(
    '/** BR-CL-06 (BT-8) differs by syntax: UNTDID 2475 in CII, UNTDID 2005 in UBL. */',
    `export const vatPointDateCodes = {\n  cii: words('${(c['BR-CL-06'] ?? []).join(' ')}'),\n  ubl: words('${(u['BR-CL-06'] ?? []).join(' ')}'),\n};`,
    '',
  );
  return out.join('\n');
}
