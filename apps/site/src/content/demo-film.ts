export function filmState(time: number) {
  const seconds = Math.max(0, Math.min(demoFilm.duration, time));
  const scene = demoFilm.steps.findIndex((step) => seconds >= step.start && seconds < step.end);
  const index = scene < 0 ? demoFilm.steps.length - 1 : scene;
  return {
    scene: index,
    seconds,
    step: demoFilm.steps[index] ?? demoFilm.steps[0],
    corrected: seconds >= 14.2,
    confirmed: seconds >= 20.2,
    delivered: seconds >= 25.5,
    accepted: seconds >= 27.5,
    paid: seconds >= 31.2,
  };
}
